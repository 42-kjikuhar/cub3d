#include "vec2/dvec2.h"

t_dvec2	dvec2_add(t_dvec2 a, t_dvec2 b)
{
	t_dvec2	sum;

	sum.x = a.x + b.x;
	sum.y = a.y + b.y;
	return (sum);
}

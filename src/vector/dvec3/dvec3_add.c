#include "cub3d.h"

t_dvec3	dvec3_add(t_dvec3 a, t_dvec3 b)
{
	t_dvec3	v;

	v.x = a.x + b.x;
	v.y = a.y + b.y;
	v.z = a.z + b.z;
	return (v);
}
